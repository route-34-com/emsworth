/** The lookbook photos, as curated in the folder (see curated.ts), with their product, colour and style.
 *  Throws if a curated photo is missing from the shoot, so a rename can't silently drop it. */
export const tagged = Object.entries(CURATED).map(([key, [cat, col, style]]) => {
  const p = photos.find((x) => `${x.folder}/${x.file}` === key);
  if (!p) throw new Error(`Curated photo not in the shoot: ${key}`);
  return { ...p, cat, col, style, person: !PRODUCT_ONLY.has(key) };
}).sort((a, b) => Number(b.person) - Number(a.person)); // photos with a person first, then the product alone
